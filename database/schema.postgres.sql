-- -----------------------------------------------------------------------------
-- Triggers updated_at
-- -----------------------------------------------------------------------------

DO $$
DECLARE
  t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'perfis','menus','usuarios','permissoes_acesso',
    'hospitais_clinicas','farmacias','cuidadores','responsaveis',
    'medicos','pacientes','remedios','paciente_anamnese',
    'consultas','atendimentos_rotina','atendimento_execucoes','agenda_eventos',
    'inicio_registros'
  ]
  LOOP
    EXECUTE format(
      'CREATE TRIGGER trg_%s_updated_at
       BEFORE UPDATE ON %I
       FOR EACH ROW EXECUTE PROCEDURE set_updated_at()',
      t, t
    );
  END LOOP;
END $$;

