-- Fase 1 / Etapa 2: faixas de referência definidas pela família ou pelo médico.
-- Sem faixas padrão: só existem se um usuário vinculado definir. Idempotente.
CREATE TABLE IF NOT EXISTS sinais_vitais_faixas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id INTEGER NOT NULL REFERENCES pacientes (id) ON UPDATE CASCADE ON DELETE CASCADE,
  tipo VARCHAR(30) NOT NULL,
  valor_min NUMERIC(6,2) NULL,
  valor_max NUMERIC(6,2) NULL,
  sistolica_min SMALLINT NULL,
  sistolica_max SMALLINT NULL,
  diastolica_min SMALLINT NULL,
  diastolica_max SMALLINT NULL,
  origem VARCHAR(20) NOT NULL DEFAULT 'familia',
  definido_por INTEGER NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uk_svf_paciente_tipo UNIQUE (paciente_id, tipo),
  CONSTRAINT ck_svf_tipo CHECK (tipo IN ('pressao','frequencia_cardiaca','glicemia','temperatura','saturacao_o2','peso')),
  CONSTRAINT ck_svf_origem CHECK (origem IN ('familia','medico')),
  CONSTRAINT ck_svf_ordem CHECK (
    (valor_min IS NULL OR valor_max IS NULL OR valor_min < valor_max)
    AND (sistolica_min IS NULL OR sistolica_max IS NULL OR sistolica_min < sistolica_max)
    AND (diastolica_min IS NULL OR diastolica_max IS NULL OR diastolica_min < diastolica_max)
  ),
  CONSTRAINT ck_svf_campos CHECK (
    (tipo = 'pressao' AND valor_min IS NULL AND valor_max IS NULL
      AND COALESCE(sistolica_min, sistolica_max, diastolica_min, diastolica_max) IS NOT NULL)
    OR (tipo <> 'pressao' AND sistolica_min IS NULL AND sistolica_max IS NULL
      AND diastolica_min IS NULL AND diastolica_max IS NULL
      AND COALESCE(valor_min, valor_max) IS NOT NULL)
  )
);
