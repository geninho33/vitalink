-- Fase 0 / Etapa 4: inscrições Web Push. Idempotente.
CREATE TABLE IF NOT EXISTS push_subscriptions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE CASCADE,
  endpoint TEXT NOT NULL,
  p256dh VARCHAR(200) NOT NULL,
  auth VARCHAR(100) NOT NULL,
  user_agent VARCHAR(500) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_success_at TIMESTAMPTZ NULL,
  CONSTRAINT uk_push_endpoint UNIQUE (endpoint)
);
CREATE INDEX IF NOT EXISTS idx_push_usuario ON push_subscriptions (usuario_id);
