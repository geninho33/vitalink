-- Fase 0 / Etapa 2: sinais vitais por paciente. Idempotente.
CREATE TABLE IF NOT EXISTS sinais_vitais (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id INTEGER NOT NULL REFERENCES pacientes (id) ON UPDATE CASCADE ON DELETE CASCADE,
  tipo VARCHAR(30) NOT NULL,
  valor NUMERIC(6,2) NULL,
  sistolica SMALLINT NULL,
  diastolica SMALLINT NULL,
  unidade VARCHAR(10) NOT NULL,
  medido_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  origem VARCHAR(20) NOT NULL DEFAULT 'manual',
  observacao VARCHAR(500) NULL,
  registrado_por INTEGER NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_sv_tipo CHECK (tipo IN ('pressao','frequencia_cardiaca','glicemia','temperatura','saturacao_o2','peso')),
  CONSTRAINT ck_sv_origem CHECK (origem IN ('manual')),
  CONSTRAINT ck_sv_valores CHECK (
    (tipo = 'pressao' AND sistolica BETWEEN 50 AND 260 AND diastolica BETWEEN 30 AND 160
       AND sistolica > diastolica AND valor IS NULL)
    OR (tipo <> 'pressao' AND valor IS NOT NULL AND sistolica IS NULL AND diastolica IS NULL)
  ),
  CONSTRAINT ck_sv_faixas CHECK (
    tipo = 'pressao'
    OR (tipo = 'frequencia_cardiaca' AND valor BETWEEN 20 AND 250)
    OR (tipo = 'glicemia' AND valor BETWEEN 20 AND 600)
    OR (tipo = 'temperatura' AND valor BETWEEN 30 AND 45)
    OR (tipo = 'saturacao_o2' AND valor BETWEEN 50 AND 100)
    OR (tipo = 'peso' AND valor BETWEEN 0.5 AND 400)
  )
);

CREATE INDEX IF NOT EXISTS idx_sv_paciente_tipo_medido
  ON sinais_vitais (paciente_id, tipo, medido_em DESC);
