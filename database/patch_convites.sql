-- Convites por link para a rede de cuidado (idempotente).
-- Guarda apenas o SHA-256 do token; o token em claro só existe no link entregue a quem convidou.
CREATE TABLE IF NOT EXISTS convites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id INTEGER NOT NULL REFERENCES pacientes (id) ON UPDATE CASCADE ON DELETE CASCADE,
  criado_por INTEGER NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL,
  papel VARCHAR(40) NOT NULL,
  token_hash CHAR(64) NOT NULL,
  rotulo VARCHAR(160) NULL,
  expires_at TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '7 days'),
  max_usos INTEGER NOT NULL DEFAULT 1,
  usado_por INTEGER NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL,
  usado_em TIMESTAMPTZ NULL,
  revogado_em TIMESTAMPTZ NULL,
  revogado_por INTEGER NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_convites_token_hash ON convites (token_hash);
CREATE INDEX IF NOT EXISTS idx_convites_paciente ON convites (paciente_id, created_at DESC);
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'convites_papel_check') THEN
    ALTER TABLE convites ADD CONSTRAINT convites_papel_check CHECK (papel IN ('responsavel', 'cuidador'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'convites_max_usos_check') THEN
    ALTER TABLE convites ADD CONSTRAINT convites_max_usos_check CHECK (max_usos = 1);
  END IF;
END $$;
