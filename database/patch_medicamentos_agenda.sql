CREATE TABLE IF NOT EXISTS medicamento_doses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  remedio_id INTEGER NOT NULL REFERENCES remedios (id) ON UPDATE CASCADE ON DELETE CASCADE,
  paciente_id INTEGER NOT NULL REFERENCES pacientes (id) ON UPDATE CASCADE ON DELETE CASCADE,
  data_hora TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL DEFAULT 'pendente',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_med_doses_remedio ON medicamento_doses (remedio_id, data_hora);
CREATE INDEX IF NOT EXISTS idx_med_doses_paciente ON medicamento_doses (paciente_id, data_hora);

CREATE TABLE IF NOT EXISTS medicamento_compras (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  remedio_id INTEGER NOT NULL REFERENCES remedios (id) ON UPDATE CASCADE ON DELETE CASCADE,
  paciente_id INTEGER NULL REFERENCES pacientes (id) ON UPDATE CASCADE ON DELETE SET NULL,
  farmacia_id INTEGER NULL REFERENCES farmacias (id) ON UPDATE CASCADE ON DELETE SET NULL,
  quantidade NUMERIC(12,2) NOT NULL,
  valor NUMERIC(12,2) NULL,
  data_compra DATE NOT NULL DEFAULT CURRENT_DATE,
  usuario_id INTEGER NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_med_compras_remedio ON medicamento_compras (remedio_id, data_compra DESC);
