-- Links temporários do relatório em PDF para o médico (idempotente). Guarda só o SHA-256 do token.
CREATE TABLE IF NOT EXISTS relatorio_links (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id INTEGER NOT NULL REFERENCES pacientes (id) ON UPDATE CASCADE ON DELETE CASCADE,
  criado_por INTEGER NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL,
  token_hash CHAR(64) NOT NULL,
  periodo_inicio DATE NOT NULL,
  periodo_fim DATE NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '72 hours'),
  revogado_em TIMESTAMPTZ NULL,
  revogado_por INTEGER NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL,
  visualizacoes INTEGER NOT NULL DEFAULT 0,
  ultima_visualizacao_em TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_relatorio_links_token ON relatorio_links (token_hash);
CREATE INDEX IF NOT EXISTS idx_relatorio_links_paciente ON relatorio_links (paciente_id, created_at DESC);
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'relatorio_links_periodo_check') THEN
    ALTER TABLE relatorio_links ADD CONSTRAINT relatorio_links_periodo_check CHECK (periodo_fim >= periodo_inicio);
  END IF;
END $$;
