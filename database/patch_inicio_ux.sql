ALTER TABLE remedios ADD COLUMN IF NOT EXISTS intervalo_horas INTEGER NULL;

CREATE TABLE IF NOT EXISTS paciente_corpo_marcas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id INTEGER NOT NULL REFERENCES pacientes (id) ON UPDATE CASCADE ON DELETE CASCADE,
  pos_x NUMERIC(6,2) NOT NULL,
  pos_y NUMERIC(6,2) NOT NULL,
  titulo VARCHAR(180) NOT NULL,
  descricao TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_corpo_marcas_paciente ON paciente_corpo_marcas (paciente_id);
