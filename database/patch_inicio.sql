-- VitaLink — Módulo Início (PostgreSQL)
-- Idempotente: pode rodar em bancos já existentes

CREATE TABLE IF NOT EXISTS inicio_registros (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL,
  paciente_id INTEGER NULL REFERENCES pacientes (id) ON UPDATE CASCADE ON DELETE SET NULL,
  titulo VARCHAR(180) NOT NULL,
  descricao TEXT NOT NULL,
  tipo TEXT NOT NULL DEFAULT 'saude'
    CHECK (tipo IN ('saude', 'aviso', 'compromisso', 'medicamento', 'outro')),
  data_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  prioridade TEXT NOT NULL DEFAULT 'media'
    CHECK (prioridade IN ('baixa', 'media', 'alta')),
  status TEXT NOT NULL DEFAULT 'ativo'
    CHECK (status IN ('ativo', 'arquivado')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_inicio_data ON inicio_registros (data_registro DESC);
CREATE INDEX IF NOT EXISTS idx_inicio_tipo ON inicio_registros (tipo);
CREATE INDEX IF NOT EXISTS idx_inicio_status ON inicio_registros (status);
CREATE INDEX IF NOT EXISTS idx_inicio_usuario ON inicio_registros (usuario_id);

DO $$
