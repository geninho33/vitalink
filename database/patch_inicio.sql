    SELECT 1 FROM pg_trigger WHERE tgname = 'trg_inicio_registros_updated_at'
  ) THEN
    CREATE TRIGGER trg_inicio_registros_updated_at
      BEFORE UPDATE ON inicio_registros
      FOR EACH ROW EXECUTE PROCEDURE set_updated_at();
  END IF;
END $$;

