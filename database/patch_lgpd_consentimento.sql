CREATE TABLE IF NOT EXISTS lgpd_documentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo VARCHAR(40) NOT NULL,
  versao VARCHAR(20) NOT NULL,
  titulo VARCHAR(200) NOT NULL,
  conteudo TEXT NOT NULL,
  obrigatorio BOOLEAN NOT NULL DEFAULT TRUE,
  vigente_desde TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_lgpd_doc_tipo CHECK (tipo IN ('politica_privacidade', 'termos_uso', 'consentimento_dados_saude')),
  CONSTRAINT uk_lgpd_doc_tipo_versao UNIQUE (tipo, versao)
);

CREATE TABLE IF NOT EXISTS lgpd_consentimentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE CASCADE,
  documento_id INTEGER NOT NULL REFERENCES lgpd_documentos (id) ON UPDATE CASCADE ON DELETE RESTRICT,
  versao VARCHAR(20) NOT NULL,
  aceito_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ip VARCHAR(64) NULL,
  user_agent VARCHAR(500) NULL,
  hash_conteudo CHAR(64) NOT NULL,
  CONSTRAINT uk_lgpd_consent_usuario_doc UNIQUE (usuario_id, documento_id)
);

CREATE INDEX IF NOT EXISTS idx_lgpd_consent_usuario ON lgpd_consentimentos (usuario_id);
CREATE INDEX IF NOT EXISTS idx_lgpd_doc_tipo_ativo ON lgpd_documentos (tipo, ativo, vigente_desde DESC);

