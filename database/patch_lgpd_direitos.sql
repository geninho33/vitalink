CREATE TABLE IF NOT EXISTS lgpd_exclusoes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE CASCADE,
  status VARCHAR(20) NOT NULL DEFAULT 'agendada',
  solicitado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  efetivar_em TIMESTAMPTZ NOT NULL,
  cancelado_em TIMESTAMPTZ NULL,
  executado_em TIMESTAMPTZ NULL,
  resumo JSONB NULL,
  erro TEXT NULL,
  CONSTRAINT ck_lgpd_exclusoes_status CHECK (status IN ('agendada', 'cancelada', 'executando', 'concluida', 'erro'))
);
