const { Router } = require('express');
const controller = require('../controllers/inicio.controller');
const medicamentos = require('../controllers/medicamentos.controller');
const corpoMarcas = require('../controllers/corpoMarcas.controller');
const sinaisVitais = require('../controllers/sinaisVitais.controller');
const doses = require('../controllers/doses.controller');
const { authenticate } = require('../middleware/auth');
const { requirePermission } = require('../middleware/rbac');

const router = Router();
const rota = controller.menuRota;

router.use(authenticate);
router.get('/', requirePermission(rota, 'ler'), controller.list);
router.get('/farmacias', requirePermission(rota, 'ler'), medicamentos.listFarmacias);
router.post('/farmacia-rapida', requirePermission(rota, 'criar'), medicamentos.farmaciaRapida);
router.get('/medicamentos', requirePermission(rota, 'ler'), medicamentos.list);
router.post('/medicamentos', requirePermission(rota, 'criar'), medicamentos.create);
router.get('/medicamentos/:id/compras', requirePermission(rota, 'ler'), medicamentos.listCompras);
router.post('/medicamentos/:id/compras', requirePermission(rota, 'criar'), medicamentos.createCompra);
router.post('/medicamentos/:id/receita', requirePermission(rota, 'editar'), medicamentos.attachReceita);
router.delete('/medicamentos/:id', requirePermission(rota, 'deletar'), medicamentos.remove);
router.get('/corpo-marcas', requirePermission(rota, 'ler'), corpoMarcas.list);
router.post('/corpo-marcas', requirePermission(rota, 'criar'), corpoMarcas.create);
router.delete('/corpo-marcas/:id', requirePermission(rota, 'deletar'), corpoMarcas.remove);
router.get('/doses', requirePermission(rota, 'ler'), doses.list);
router.post('/doses/:id/tomei', requirePermission(rota, 'editar'), doses.tomei);
router.post('/doses/:id/pular', requirePermission(rota, 'editar'), doses.pular);
router.post('/doses/:id/adiar', requirePermission(rota, 'editar'), doses.adiar);
router.get('/lembretes-config', requirePermission(rota, 'ler'), doses.getConfig);
router.put('/lembretes-config', requirePermission(rota, 'editar'), doses.putConfig);
router.get('/sinais-vitais/faixas', requirePermission(rota, 'ler'), sinaisVitais.listFaixas);
router.put('/sinais-vitais/faixas', requirePermission(rota, 'editar'), sinaisVitais.salvarFaixa);
router.delete('/sinais-vitais/faixas', requirePermission(rota, 'editar'), sinaisVitais.removerFaixa);
router.get('/sinais-vitais', requirePermission(rota, 'ler'), sinaisVitais.list);
router.post('/sinais-vitais', requirePermission(rota, 'criar'), sinaisVitais.create);
router.delete('/sinais-vitais/:id', requirePermission(rota, 'deletar'), sinaisVitais.remove);
router.get('/:id', requirePermission(rota, 'ler'), controller.getById);
router.post('/', requirePermission(rota, 'criar'), controller.create);
router.put('/:id', requirePermission(rota, 'editar'), controller.update);
router.delete('/:id', requirePermission(rota, 'deletar'), controller.remove);

module.exports = router;
